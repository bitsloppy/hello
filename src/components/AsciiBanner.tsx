"use client";

import styles from "./AsciiBanner.module.css";

const LINES = [
  ".########..####.########.....######..##........#######..########..########..##....##",
  ".##.....##..##.....##.......##....##.##.......##.....##.##.....##.##.....##..##..##.",
  ".##.....##..##.....##.......##.......##.......##.....##.##.....##.##.....##...####..",
  ".########...##.....##........######..##.......##.....##.########..########.....##...",
  ".##.....##..##.....##.............##.##.......##.....##.##........##...........##...",
  ".##.....##..##.....##.......##....##.##.......##.....##.##........##...........##...",
  ".########..####....##........######..########..#######..##........##...........##...",
];

export default function AsciiBanner() {
  return (
    <div className={styles.wrap}>
      <pre className={styles.banner} aria-label="BIT SLOPPY">
        {LINES.map((line, li) => (
          <span key={li}>
            {line.split("").map((ch, ci) =>
              ch === "#" ? (
                <span key={ci} className={styles.hash}>#</span>
              ) : (
                <span key={ci} className={styles.dot}>.</span>
              )
            )}
            {"\n"}
          </span>
        ))}
      </pre>
    </div>
  );
}
